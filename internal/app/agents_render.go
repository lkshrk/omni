const agentsRenderedMarker = "# Generated by omni from the agents settings (settings.d/agents.json); edit those, not this file."

type renderedManifest struct {
	Name         string               `yaml:"name"`
	Version      string               `yaml:"version"`
	Targets      []string             `yaml:"targets,omitempty"`
	Dependencies renderedDependencies `yaml:"dependencies"`
}

type renderedDependencies struct {
	APM []apmPackageDep `yaml:"apm,omitempty"`
	MCP []renderedMCP   `yaml:"mcp,omitempty"`
	LSP []apmLSPDep     `yaml:"lsp,omitempty"`
}

type renderedMCP struct {
	Name      string            `yaml:"name"`
	Targets   *[]string         `yaml:"targets,omitempty,flow"`
	Registry  bool              `yaml:"registry"`
	Transport string            `yaml:"transport"`
	URL       string            `yaml:"url,omitempty"`
	Command   string            `yaml:"command,omitempty"`
	Args      []string          `yaml:"args,omitempty"`
	Cwd       string            `yaml:"cwd,omitempty"`
	Env       map[string]string `yaml:"env,omitempty"`
	Headers   map[string]string `yaml:"headers,omitempty"`
	Tools     []string          `yaml:"tools,omitempty"`
	Extra     map[string]any    `yaml:"extra,omitempty"`
}

func selectedAgentNames(cfg *config.RootConfig, hostname string) map[string]bool {
	groups, _, _ := effectiveHostGroups(cfg, cfg.Groups, hostname)
	selected := make(map[string]bool)
	for _, group := range groups {
		for _, name := range group.Agents {
			selected[name] = true
		}
	}
	return selected
}

func renderAgentsManifest(cfg *config.RootConfig, hostname string) ([]byte, error) {
	agents := cfg.Agents
	selected := selectedAgentNames(cfg, hostname)
	manifest := renderedManifest{Name: "omni", Version: "1.0.0", Targets: slices.Clone(agents.Targets)}
	for _, pkg := range agents.Packages {
		if !selected[pkg.EntryName()] {
			continue
		}
		manifest.Dependencies.APM = append(manifest.Dependencies.APM, apmPackageDep{
			Git: pkg.Source, Path: pkg.Path, Ref: pkg.Ref, Targets: slices.Clone(pkg.Targets),
		})
	}
	for _, server := range agents.MCP {
		if !selected[server.Name] {
			continue
		}
		extra, err := server.RenderedExtra()
		if err != nil {
			return nil, fmt.Errorf("agents.mcp %q: %w", server.Name, err)
		}
		if extra != nil {
			extra = yamlSafeNumbers(extra).(map[string]any)
		}
		manifest.Dependencies.MCP = append(manifest.Dependencies.MCP, renderedMCP{
			Name: server.Name, Targets: cloneOptionalTargets(server.Targets), Transport: server.Transport, URL: server.URL,
			Command: server.Command, Args: server.Args, Cwd: server.Cwd, Env: server.Env,
			Headers: server.Headers, Tools: server.Tools, Extra: extra,
		})
	}
	for _, server := range agents.LSP {
		if !selected[server.Name] {
			continue
		}
		manifest.Dependencies.LSP = append(manifest.Dependencies.LSP, apmLSPDep{
			Name: server.Name, Transport: server.Transport, Command: server.Command, Args: server.Args,
			Env: server.Env, Cwd: server.Cwd, ExtensionToLanguage: server.ExtensionToLanguage,
			Initialization: yamlSafeNumbers(server.InitializationOptions), WorkspaceFolder: server.WorkspaceFolder,
			StartupTimeout: server.StartupTimeout, ShutdownTimeout: server.ShutdownTimeout,
			RestartOnCrash: server.RestartOnCrash, MaxRestarts: server.MaxRestarts,
		})
	}
	body, err := encodeAPMManifest(manifest)
	if err != nil {
		return nil, err
	}
	return []byte(agentsRenderedMarker + "\n" + body), nil
}

// yamlSafeNumbers writes floats in plain decimal with a dot, since yaml.v3 would emit 1e+06, which YAML 1.1 reads as text.
func yamlSafeNumbers(value any) any {
	switch value := value.(type) {
	case float64:
		text := strconv.FormatFloat(value, 'f', -1, 64)
		if !strings.Contains(text, ".") {
			text += ".0"
		}
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!float", Value: text}
	case json.Number:
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!float", Value: value.String()}
	case map[string]any:
		out := make(map[string]any, len(value))
		for key, item := range value {
			out[key] = yamlSafeNumbers(item)
		}
		return out
	case []any:
		out := make([]any, len(value))
		for i, item := range value {
			out[i] = yamlSafeNumbers(item)
		}
		return out
	default:
		return value
	}
}

// cloneOptionalTargets keeps nil (every client) apart from empty (no client).
func cloneOptionalTargets(targets *[]string) *[]string {
	if targets == nil {
		return nil
	}
	cloned := append([]string{}, *targets...)
	return &cloned
}
